/**
 * Builds CSS custom properties + TS types from the DTCG token files in /Flow/tokens.
 *
 * Tiers emitted:
 *   base.css      Base primitives          -> --base-*        (resolution targets ONLY, never reference in components)
 *   semantic.css  Semantic/Component/...   -> --semantic-*, --component-*, --feature-*, --merchandise-*, --legacy-*
 *   typography.css  text styles            -> .ds-text-* classes + per-style vars
 *   elevation.css   effect styles          -> --semantic-elevation-*
 *
 * Aliases ({A.B.C}) are emitted as var(--a-b-c) rather than being flattened, so the
 * Light/Dark theme override on [data-theme] cascades through the whole chain.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const TOKENS_DIR = process.env.DS_TOKENS_DIR ?? join(__dirname, '../../tokens');
const OUT_DIR = join(__dirname, '../src/tokens');

const read = (f) => JSON.parse(readFileSync(join(TOKENS_DIR, f), 'utf8'));

/** Figma font-weight names have no CSS meaning; map to numeric weights. */
const FONT_WEIGHTS = {
  thin: 100,
  extralight: 200,
  light: 300,
  regular: 400,
  normal: 400,
  medium: 500,
  semibold: 600,
  bold: 700,
  extrabold: 800,
  black: 900,
};

/** `BorderRadius.100%` and `Opacity.5%` are not valid custom-property idents, and a
 *  few typography names contain spaces (e.g. `Tag.S Bold`). */
function segment(s) {
  if (s === '100%') return 'full';
  const base = s.endsWith('%') ? s.slice(0, -1) : s;
  return base
    .replace(/[\s_]+/g, '-')
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/[^a-zA-Z0-9-]/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '')
    .toLowerCase();
}

const toVarName = (path) => `--${path.map(segment).join('-')}`;

const ALIAS = /^\{([^}]+)\}$/;
const isAlias = (v) => typeof v === 'string' && ALIAS.test(v);
const aliasToVar = (v) => `var(${toVarName(v.match(ALIAS)[1].split('.'))})`;

/** Resolve a scalar token value into a CSS-valid string. */
function cssValue(value, type, path) {
  if (isAlias(value)) return aliasToVar(value);

  const key = path.join('.').toLowerCase();

  if (key.includes('fontweight')) {
    const w = FONT_WEIGHTS[String(value).toLowerCase().replace(/[\s-]/g, '')];
    if (w) return String(w);
  }

  if (key.includes('fontfamily')) {
    return `'${value}', system-ui, -apple-system, sans-serif`;
  }

  // Opacity is authored as 0-100 but CSS opacity is 0-1.
  if (key.includes('opacity')) {
    const n = Number(value);
    if (Number.isFinite(n)) return n > 1 ? String(n / 100) : String(n);
  }

  if (type === 'number' && typeof value === 'number') return String(value);
  return String(value);
}

function shadowValue(value) {
  const layers = Array.isArray(value) ? value : [value];
  return layers
    .map((l) => {
      const color = isAlias(l.color) ? aliasToVar(l.color) : l.color;
      const inset = l.inset ? 'inset ' : '';
      return `${inset}${l.offsetX} ${l.offsetY} ${l.blur} ${l.spread} ${color}`;
    })
    .join(', ');
}

/** Depth-first walk over a DTCG tree, yielding leaf tokens. */
function walk(node, path, out) {
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith('$')) continue;
    if (child && typeof child === 'object' && '$value' in child) {
      out.push({ path: [...path, key], type: child.$type, value: child.$value, description: child.$description });
    } else if (child && typeof child === 'object') {
      walk(child, [...path, key], out);
    }
  }
  return out;
}

function declarations(tokens, { skipTypes = [] } = {}) {
  const lines = [];
  for (const t of tokens) {
    if (skipTypes.includes(t.type)) continue;
    const name = toVarName(t.path);
    const value = t.type === 'shadow' ? shadowValue(t.value) : cssValue(t.value, t.type, t.path);
    if (t.description) lines.push(`  /* ${t.description.replace(/\*\//g, '')} */`);
    lines.push(`  ${name}: ${value};`);
  }
  return lines.join('\n');
}

const banner = (src) =>
  `/* AUTO-GENERATED by scripts/build-tokens.mjs from ${src}. Do not edit by hand. */\n`;

mkdirSync(OUT_DIR, { recursive: true });

// ---------------------------------------------------------------- base tier
const baseTokens = walk(read('Base.value.tokens.json'), [], []);
writeFileSync(
  join(OUT_DIR, 'base.css'),
  `${banner('Base.value.tokens.json')}
/* Primitive values. These exist only so semantic tokens have something to resolve
   to — components must never reference a --base-* variable directly. */
:root {
${declarations(baseTokens)}
}
`,
);

// ------------------------------------------------------------ semantic tier
const light = walk(read('\u{1F512} Theme.Light.tokens.json'), [], []);
const dark = walk(read('\u{1F512} Theme.Dark.tokens.json'), [], []);

writeFileSync(
  join(OUT_DIR, 'semantic.css'),
  `${banner('\u{1F512} Theme.{Light,Dark}.tokens.json')}
/* The only tier components are allowed to consume. */
:root,
[data-theme='light'] {
${declarations(light)}
}

[data-theme='dark'] {
${declarations(dark)}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${declarations(dark)
  .split('\n')
  .map((l) => (l ? `  ${l}` : l))
  .join('\n')}
  }
}
`,
);

// ------------------------------------------------------------- typography
const textTokens = walk(read('text.styles.tokens.json'), [], []);
const typoVars = [];
const typoClasses = [];

for (const t of textTokens) {
  if (t.type !== 'typography') continue;
  const base = toVarName(t.path);
  const v = t.value;
  const resolve = (x) => (isAlias(x) ? aliasToVar(x) : x);

  const lineHeight =
    typeof v.lineHeight === 'string' && v.lineHeight.endsWith('%')
      ? String(Number(v.lineHeight.slice(0, -1)) / 100)
      : resolve(v.lineHeight);
  const letterSpacing =
    typeof v.letterSpacing === 'string' && v.letterSpacing.endsWith('%')
      ? v.letterSpacing === '0%'
        ? '0'
        : `${Number(v.letterSpacing.slice(0, -1)) / 100}em`
      : resolve(v.letterSpacing);

  typoVars.push(
    `  ${base}-font-family: ${resolve(v.fontFamily)};`,
    `  ${base}-font-size: ${resolve(v.fontSize)};`,
    `  ${base}-font-weight: ${resolve(v.fontWeight)};`,
    `  ${base}-line-height: ${lineHeight};`,
    `  ${base}-letter-spacing: ${letterSpacing};`,
  );

  const cls = `.ds-text-${t.path.slice(2).map(segment).join('-')}`;
  typoClasses.push(
    `${cls} {
  font-family: var(${base}-font-family);
  font-size: var(${base}-font-size);
  font-weight: var(${base}-font-weight);
  line-height: var(${base}-line-height);
  letter-spacing: var(${base}-letter-spacing);${
    v.textTransform && v.textTransform !== 'none' ? `\n  text-transform: ${v.textTransform};` : ''
  }${v.textDecoration && v.textDecoration !== 'none' ? `\n  text-decoration: ${v.textDecoration};` : ''}
}`,
  );
}

writeFileSync(
  join(OUT_DIR, 'typography.css'),
  `${banner('text.styles.tokens.json')}
:root {
${typoVars.join('\n')}
}

${typoClasses.join('\n\n')}
`,
);

// -------------------------------------------------------------- elevation
const effectTokens = walk(read('effect.styles.tokens.json'), [], []);
writeFileSync(
  join(OUT_DIR, 'elevation.css'),
  `${banner('effect.styles.tokens.json')}
:root {
${declarations(effectTokens)}
}
`,
);

// ------------------------------------------------------------------ index
writeFileSync(
  join(OUT_DIR, 'index.css'),
  `${banner('the token pipeline')}@import './base.css';
@import './semantic.css';
@import './typography.css';
@import './elevation.css';
`,
);

// --------------------------------------------------------------- TS types
const consumable = [...light, ...textTokens, ...effectTokens];
const names = [...new Set(consumable.map((t) => toVarName(t.path)))].sort();
const typographyNames = textTokens
  .filter((t) => t.type === 'typography')
  .map((t) => `ds-text-${t.path.slice(2).map(segment).join('-')}`)
  .sort();

writeFileSync(
  join(OUT_DIR, 'tokens.ts'),
  `${banner('the token pipeline')}
/** Every token a component is allowed to reference. \`--base-*\` is deliberately excluded. */
export type TokenName =
${names.map((n) => `  | '${n}'`).join('\n')};

/** Typography utility classes emitted into typography.css. */
export type TypographyClass =
${typographyNames.map((n) => `  | '${n}'`).join('\n')};

/** Type-safe \`var()\` reference. */
export const token = (name: TokenName, fallback?: string): string =>
  fallback ? \`var(\${name}, \${fallback})\` : \`var(\${name})\`;

export type Theme = 'light' | 'dark';
`,
);

const baseRefs = light.filter((t) => isAlias(t.value) && t.value.startsWith('{Base.')).length;

console.log(`tokens: ${baseTokens.length} base, ${light.length} themed (light), ${dark.length} themed (dark)`);
console.log(`        ${textTokens.length} text styles, ${effectTokens.length} effect styles`);
console.log(`        ${names.length} consumable variables -> src/tokens/`);
console.log(`note:   ${baseRefs} themed tokens alias Base directly (expected — that is the resolution layer)`);
