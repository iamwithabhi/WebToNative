/**
 * Generates tree-shakeable React icon components from the SVGs in /Flow/icons.
 *
 * The source SVGs hardcode `fill="#1F1F1F"`. That is rewritten to `currentColor`
 * so colour is driven by the CSS `color` property, which <Icon> binds to a
 * semantic icon token. Any other colour in a file is left alone (there is one
 * two-tone icon, profile-f-sys).
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ICONS_DIR = process.env.DS_ICONS_DIR ?? join(__dirname, '../../icons');
const OUT_DIR = join(__dirname, '../src/icons/generated');

const MONO = /^#1f1f1f$/i;

const SVG_ATTR_MAP = {
  'fill-rule': 'fillRule',
  'clip-rule': 'clipRule',
  'stroke-width': 'strokeWidth',
  'stroke-linecap': 'strokeLinecap',
  'stroke-linejoin': 'strokeLinejoin',
  'stroke-dasharray': 'strokeDasharray',
  'stroke-dashoffset': 'strokeDashoffset',
  'stroke-miterlimit': 'strokeMiterlimit',
  'stop-color': 'stopColor',
  'stop-opacity': 'stopOpacity',
  'fill-opacity': 'fillOpacity',
  'stroke-opacity': 'strokeOpacity',
  'clip-path': 'clipPath',
  'xlink:href': 'xlinkHref',
  'gradientUnits': 'gradientUnits',
  'gradientTransform': 'gradientTransform',
};

function toPascal(file) {
  const cleaned = file
    .replace(/\.svg$/i, '')
    .split(/[-_]/)
    .filter((part) => part && part !== 'sys')
    .map((part) => (part === 'f' ? 'filled' : part));

  let name = cleaned.map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join('');
  if (/^\d/.test(name)) name = `Icon${name}`;
  return name;
}

/** Convert raw SVG markup to JSX-safe markup. */
function toJsx(markup) {
  return markup
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/fill="([^"]+)"/gi, (m, color) => (MONO.test(color) ? 'fill="currentColor"' : m))
    .replace(/([a-zA-Z-]+:?[a-zA-Z-]*)=/g, (m, attr) => `${SVG_ATTR_MAP[attr] ?? attr}=`)
    .replace(/\s+/g, ' ')
    .trim();
}

const files = readdirSync(ICONS_DIR)
  .filter((f) => f.toLowerCase().endsWith('.svg'))
  .sort();

rmSync(OUT_DIR, { recursive: true, force: true });
mkdirSync(OUT_DIR, { recursive: true });

const seen = new Map();
const collisions = [];
const entries = [];

for (const file of files) {
  const raw = readFileSync(join(ICONS_DIR, file), 'utf8');

  const viewBox = raw.match(/viewBox="([^"]+)"/)?.[1] ?? '0 0 24 24';
  const inner = raw.replace(/^[\s\S]*?<svg[^>]*>/i, '').replace(/<\/svg>[\s\S]*$/i, '');

  let name = toPascal(file);
  if (seen.has(name)) {
    collisions.push(`${file} -> ${name} (already from ${seen.get(name)})`);
    let n = 2;
    while (seen.has(`${name}${n}`)) n += 1;
    name = `${name}${n}`;
  }
  seen.set(name, file);

  const componentName = `${name}Icon`;
  writeFileSync(
    join(OUT_DIR, `${componentName}.tsx`),
    `// AUTO-GENERATED from icons/${file}. Do not edit by hand.
import { Icon, type IconProps } from '../Icon';

export function ${componentName}(props: IconProps) {
  return (
    <Icon viewBox="${viewBox}" {...props}>
      ${toJsx(inner)}
    </Icon>
  );
}
`,
  );

  entries.push({ name, componentName, file });
}

writeFileSync(
  join(OUT_DIR, 'index.ts'),
  `// AUTO-GENERATED by scripts/build-icons.mjs. Do not edit by hand.
${entries.map((e) => `export { ${e.componentName} } from './${e.componentName}';`).join('\n')}
`,
);

writeFileSync(
  join(OUT_DIR, 'registry.ts'),
  `// AUTO-GENERATED by scripts/build-icons.mjs. Do not edit by hand.
${entries.map((e) => `import { ${e.componentName} } from './${e.componentName}';`).join('\n')}

/** Every icon keyed by name — use for dynamic lookup. Prefer direct imports where possible. */
export const icons = {
${entries.map((e) => `  '${e.name}': ${e.componentName},`).join('\n')}
} as const;

export type IconName = keyof typeof icons;

export const iconNames = Object.keys(icons) as IconName[];
`,
);

console.log(`icons:  ${entries.length} components -> src/icons/generated/`);
if (collisions.length) {
  console.log(`warn:   ${collisions.length} name collision(s), suffixed numerically:`);
  for (const c of collisions) console.log(`          ${c}`);
}
